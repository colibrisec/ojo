func TestYarnLockParser_Classic(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "yarn.lock", `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0", "@babel/code-frame@^7.8.3":
  version "7.8.3"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-7.8.3.tgz#abc"
  integrity sha512-abc
  dependencies:
    "@babel/highlight" "^7.8.3"

lodash@^4.17.15, lodash@^4.17.20:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#abc"

"string-width-cjs@npm:string-width@^4.2.0":
  version "4.2.3"
  resolved "https://registry.yarnpkg.com/string-width/-/string-width-4.2.3.tgz#abc"

"local-thing@file:../local-thing":
  version "1.0.0"
`)

	pkgs, err := yarnLockParser{}.Parse(dir + "/yarn.lock")
	if err != nil {
		t.Fatal(err)
	}
	// The nested `"@babel/highlight" "^7.8.3"` dependency line must not be
	// read as an entry; the alias resolves to the real package name.
	assertPackages(t, pkgs, model.EcosystemNpm, "@babel/code-frame@7.8.3", "lodash@4.17.21", "string-width@4.2.3")
}

