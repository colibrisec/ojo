package manifest

import (
	"sort"
	"testing"

	"github.com/colibrisec/ojo/internal/model"
)

// nameVersions flattens pkgs to sorted "name@version" strings, so a test can
// compare against a parser whose output order follows map iteration.
func nameVersions(pkgs []model.Package) []string {
	out := make([]string, 0, len(pkgs))
	for _, p := range pkgs {
		out = append(out, p.Name+"@"+p.Version)
	}
	sort.Strings(out)
	return out
}

func assertPackages(t *testing.T, pkgs []model.Package, eco model.Ecosystem, want ...string) {
	t.Helper()
	got := nameVersions(pkgs)
	sort.Strings(want)
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("got %v, want %v", got, want)
		}
	}
	for _, p := range pkgs {
		if p.Ecosystem != eco {
			t.Errorf("%s: ecosystem %q, want %q", p.Name, p.Ecosystem, eco)
		}
	}
}

func TestUvLockParser(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "uv.lock", `version = 1
requires-python = ">=3.12"

[[package]]
name = "myapp"
version = "0.1.0"
source = { virtual = "." }
dependencies = [
    { name = "requests" },
]

[[package]]
name = "shared-lib"
version = "0.2.0"
source = { editable = "libs/shared" }

[[package]]
name = "requests"
version = "2.31.0"
source = { registry = "https://pypi.org/simple" }
sdist = { url = "https://files.pythonhosted.org/requests-2.31.0.tar.gz", hash = "sha256:abc", size = 1 }

[[package]]
name = "forked"
version = "1.4.0"
source = { git = "https://github.com/example/forked?rev=abc#abc" }
`)

	pkgs, err := uvLockParser{}.Parse(dir + "/uv.lock")
	if err != nil {
		t.Fatal(err)
	}
	// The project itself and an editable workspace member aren't published
	// packages; a git dependency still has a name and version worth checking.
	assertPackages(t, pkgs, model.EcosystemPyPI, "requests@2.31.0", "forked@1.4.0")
}

