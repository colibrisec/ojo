func TestPnpmLockParser(t *testing.T) {
	cases := map[string]string{
		"v5": `lockfileVersion: 5.4

packages:

  /@babel/core/7.0.0:
    resolution: {integrity: sha512-abc}
    dev: false

  /lodash/4.17.21:
    resolution: {integrity: sha512-abc}

  /react-dom/17.0.2_react@17.0.2:
    resolution: {integrity: sha512-abc}
`,
		"v6": `lockfileVersion: '6.0'

packages:

  /@babel/core@7.0.0:
    resolution: {integrity: sha512-abc}

  /lodash@4.17.21:
    resolution: {integrity: sha512-abc}

  /react-dom@17.0.2(react@17.0.2):
    resolution: {integrity: sha512-abc}
`,
		"v9": `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      lodash:
        specifier: ^4.17.21
        version: 4.17.21

packages:

  '@babel/core@7.0.0':
    resolution: {integrity: sha512-abc}

  lodash@4.17.21:
    resolution: {integrity: sha512-abc}

  react-dom@17.0.2:
    resolution: {integrity: sha512-abc}

  forked@https://codeload.github.com/example/forked/tar.gz/abc:
    resolution: {tarball: https://codeload.github.com/example/forked/tar.gz/abc}

snapshots:

  react-dom@17.0.2(react@17.0.2):
    dependencies:
      react: 17.0.2
`,
	}
	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			write(t, dir, "pnpm-lock.yaml", content)
			pkgs, err := pnpmLockParser{}.Parse(dir + "/pnpm-lock.yaml")
			if err != nil {
				t.Fatal(err)
			}
			assertPackages(t, pkgs, model.EcosystemNpm, "@babel/core@7.0.0", "lodash@4.17.21", "react-dom@17.0.2")
		})
	}
}

func TestPodfileLockParser(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "Podfile.lock", `PODS:
  - Alamofire (5.9.1)
  - Firebase/Core (10.24.0):
    - Firebase/CoreOnly
    - FirebaseAnalytics (~> 10.24.0)
  - Firebase/CoreOnly (10.24.0):
    - FirebaseCore (= 10.24.0)
  - FirebaseCore (10.24.0)

DEPENDENCIES:
  - Alamofire (~> 5.9)
  - Firebase/Core

SPEC REPOS:
  trunk:
    - Alamofire
    - Firebase

SPEC CHECKSUMS:
  Alamofire: abc

PODFILE CHECKSUM: abc

COCOAPODS: 1.15.2
`)

	pkgs, err := podfileLockParser{}.Parse(dir + "/Podfile.lock")
	if err != nil {
		t.Fatal(err)
	}
	// Subspecs collapse into their root pod, reported once.
	assertPackages(t, pkgs, model.EcosystemCocoaPods, "Alamofire@5.9.1", "Firebase@10.24.0", "FirebaseCore@10.24.0")
}

func TestNpmLockParser_ReadsLicense(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "package-lock.json", `{"lockfileVersion": 3, "packages": {
  "": {"name": "app", "version": "1.0.0"},
  "node_modules/left-pad": {"version": "1.3.0", "license": "WTFPL"}
}}`)

	pkgs, err := npmLockParser{}.Parse(dir + "/package-lock.json")
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 1 || pkgs[0].License != "WTFPL" {
		t.Fatalf("unexpected packages: %+v", pkgs)
	}
}
